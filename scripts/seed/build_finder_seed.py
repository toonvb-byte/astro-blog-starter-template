"""Generate goal_finder_seed.sql from finder-data.json (single source of truth).
Run: python3 scripts/seed/build_finder_seed.py > scripts/seed/goal_finder_seed.sql
Apply (after review): npx wrangler d1 execute nutrimetrics-db --remote --file scripts/seed/goal_finder_seed.sql
"""
import json, os
d = json.load(open(os.path.join(os.path.dirname(__file__), "finder-data.json")))
q = lambda v: "NULL" if v is None else (str(v) if isinstance(v, (int, float)) and not isinstance(v, bool) else "'" + str(v).replace("'", "''") + "'")
b = lambda v: "1" if v else "0"
out = ["-- generated by build_finder_seed.py — do not edit by hand", "PRAGMA foreign_keys = ON;"]
checked = d["meta"]["checked"]
ing_id = {i["id"]: n for n, i in enumerate(d["ingredients"], 1001)}
goal_id = {g["id"]: n for n, g in enumerate(d["goals"], 1)}
for i in d["ingredients"]:
    n = ing_id[i["id"]]
    out.append(f"INSERT INTO ingredients (id, slug, norm_unit, norm_amount, effective_amount, upper_amount) VALUES ({n}, {q(i['id'])}, {q(i['unit'])}, {q(i['effective'])}, {q(i['effective'])}, {q(i.get('upper'))}) "
               f"ON CONFLICT(slug) DO UPDATE SET effective_amount=excluded.effective_amount, upper_amount=excluded.upper_amount;")
    for loc in ("en", "es"):
        out.append(f"INSERT OR REPLACE INTO ingredient_i18n VALUES ((SELECT id FROM ingredients WHERE slug={q(i['id'])}), {q(loc)}, {q(i[loc])}, {q((i.get('tip') or {}).get(loc))}, {q((i.get('caution') or {}).get(loc))});")
for s, g in enumerate(d["goals"]):
    out.append(f"INSERT OR REPLACE INTO goals VALUES ({goal_id[g['id']]}, {q(g['id'])}, {q(g['icon'])}, {s});")
    for loc in ("en", "es"):
        out.append(f"INSERT OR REPLACE INTO goal_i18n (goal_id, locale, name, description, warning) VALUES ({goal_id[g['id']]}, {q(loc)}, {q(g[loc])}, {q(g['desc'][loc])}, {q((g.get('warn') or {}).get(loc))});")
ING = lambda slug: f"(SELECT id FROM ingredients WHERE slug={q(slug)})"
for gi in d["goalIngredients"]:
    out.append(f"INSERT OR REPLACE INTO goal_ingredients (goal_id, ingredient_id, evidence, eu_claim, deficiency_only) VALUES ({goal_id[gi['g']]}, {ING(gi['i'])}, {gi['ev']}, {b(gi['claim'])}, {b(gi.get('cond'))});")
    for loc in ("en", "es"):
        out.append(f"INSERT OR REPLACE INTO goal_ingredient_i18n VALUES ({goal_id[gi['g']]}, {ING(gi['i'])}, {q(loc)}, {q(gi[loc])});")
for n, p in enumerate(d["products"], 5001):
    first = p["ingredients"][0]["i"] if p["ingredients"] else None
    out.append(f"INSERT OR REPLACE INTO products (id, brand, name, ingredient_id, pack_label, vegan, verified, source_url, label_partial, excluded_reason) VALUES "
               f"({n}, {q(p['brand'])}, {q(p['name'])}, {ING(first) if first else 'NULL'}, {q(p.get('pack'))}, {q(1 if p.get('vegan') else None)}, 0, {q(p['source'])}, {b(p.get('partial'))}, {q(p.get('excluded'))});")
    for loc in ("en", "es"):
        out.append(f"INSERT OR REPLACE INTO product_i18n (product_id, locale, slug, display_name, dose_label) VALUES ({n}, {q(loc)}, {q(p['id'])}, {q(p['name'])}, {q((p.get('dose') or {}).get(loc))});")
    for x in p["ingredients"]:
        out.append(f"INSERT OR REPLACE INTO product_ingredients VALUES ({n}, {ING(x['i'])}, {q(x.get('amt'))}, {q(x.get('form'))});")
    for c, st in (p.get("markets") or {}).items():
        out.append(f"INSERT OR REPLACE INTO product_markets VALUES ({n}, {q(c)}, {q(st)}, {q(p.get('checked', checked))});")
    out.append(f"DELETE FROM product_notes WHERE product_id={n};")
    for f in p.get("flags", []):
        for loc in ("en", "es"):
            out.append(f"INSERT INTO product_notes (product_id, locale, text) VALUES ({n}, {q(loc)}, {q(f[loc])});")
print("\n".join(out))
