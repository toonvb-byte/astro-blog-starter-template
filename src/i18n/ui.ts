const DATE_FMT: Record<Locale, string> = { en: "en-GB", es: "es-ES" };
export function formatDate(d: Date, locale: Locale) {
	return d.toLocaleDateString(DATE_FMT[locale], { day: "numeric", month: "short", year: "numeric" });
}
export function formatPrice(n: number, locale: Locale) {
	return new Intl.NumberFormat(DATE_FMT[locale], { style: "currency", currency: "EUR" }).format(n);
}
